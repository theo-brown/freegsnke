"""Tests for the multi-droplet composite profile (freegsnke.droplets)."""

from pathlib import Path

import numpy as np
import pytest

from freegsnke import GSstaticsolver, build_machine, equilibrium_update
from freegsnke.droplets import DoubleDroplet, Droplets
from freegsnke.gradshafranov import Greens
from freegsnke.jtor_update import ConstrainPaxisIp

REPO_ROOT = Path(__file__).resolve().parents[2]
MACHINE_CONFIG_DIR = REPO_ROOT / "machine_configs" / "MAST-U"

# Coil currents [A] holding two diverted droplets centred at R~0.76 m,
# Z~+/-1 m (100 kA each), found with an inverse solve.
DROPLET_COIL_CURRENTS = {
    "Solenoid": 0.0,
    "PX": -7045.0,
    "D1": 25295.0,
    "D2": 13020.0,
    "D3": 4056.0,
    "Dp": -13650.0,
    "D5": 83.0,
    "D6": -6959.0,
    "D7": -134.0,
    "P4": 9869.0,
    "P5": -4369.0,
    "P6": 0.0,
}
R_AXIS, Z_AXIS = 0.757, 0.995


@pytest.fixture(scope="module")
def tokamak():
    return build_machine.tokamak(
        active_coils_path=str(MACHINE_CONFIG_DIR / "MAST-U_like_active_coils.pickle"),
        passive_coils_path=str(MACHINE_CONFIG_DIR / "MAST-U_like_passive_coils.pickle"),
        limiter_path=str(MACHINE_CONFIG_DIR / "MAST-U_like_limiter.pickle"),
        wall_path=str(MACHINE_CONFIG_DIR / "MAST-U_like_wall.pickle"),
    )


@pytest.fixture()
def eq(tokamak):
    eq = equilibrium_update.Equilibrium(
        tokamak=tokamak, Rmin=0.1, Rmax=2.0, Zmin=-2.2, Zmax=2.2, nx=65, ny=129
    )
    for name, current in DROPLET_COIL_CURRENTS.items():
        eq.tokamak.set_coil_current(name, current)
    return eq


def droplet_guess(eq, currents, centres, width=0.13):
    """Plasma flux generated by Gaussian current blobs (initial guess)."""
    psi = np.zeros_like(eq.R)
    for Ip, (Rc, Zc) in zip(currents, centres):
        w = np.exp(-((eq.R - Rc) ** 2 + (eq.Z - Zc) ** 2) / width**2)
        w *= eq.limiter_handler.mask_inside_limiter
        w *= Ip / np.sum(w)
        for i, j in zip(*np.nonzero(w > 1e-3 * np.amax(w))):
            psi += w[i, j] * Greens(eq.R[i, j], eq.Z[i, j], eq.R, eq.Z)
    return psi


def make_profiles(eq, Ip_upper, Ip_lower):
    upper = ConstrainPaxisIp(eq, 3e3, Ip_upper, 0.5, alpha_m=1.8, alpha_n=1.2)
    lower = ConstrainPaxisIp(eq, 3e3, Ip_lower, 0.5, alpha_m=1.8, alpha_n=1.2)
    return DoubleDroplet(eq, upper, lower, Z_split=0.0)


def solve(eq, Ip_upper, Ip_lower):
    profiles = make_profiles(eq, Ip_upper, Ip_lower)
    eq.set_plasma_psi(
        droplet_guess(
            eq,
            [Ip_upper, Ip_lower],
            [(R_AXIS, Z_AXIS), (R_AXIS, -Z_AXIS)],
        )
    )
    solver = GSstaticsolver.NKGSsolver(eq)
    solver.forward_solve(eq, profiles, 1e-8, suppress=True)
    assert solver.relative_change < 1e-8
    return profiles


def test_double_droplet_forward_solve(eq):
    profiles = solve(eq, 1e5, 1e5)
    upper, lower = profiles.droplets
    dR = eq.R_1D[1] - eq.R_1D[0]
    dZ = eq.Z_1D[1] - eq.Z_1D[0]

    # one magnetic axis per droplet, where the coils were designed to hold them
    assert profiles.opt.shape == (2, 3)
    assert np.allclose(upper.opt[0, :2], [R_AXIS, Z_AXIS], atol=2 * max(dR, dZ))
    assert np.allclose(lower.opt[0, :2], [R_AXIS, -Z_AXIS], atol=2 * max(dR, dZ))

    # each droplet is diverted by its own X-point (not a shared midplane one)
    assert upper.has_relevant_xpoint and lower.has_relevant_xpoint
    assert not upper.flag_limiter and not lower.flag_limiter
    assert upper.xpt[0, 1] > 0.5 and lower.xpt[0, 1] < -0.5
    assert np.isclose(upper.psi_bndry, upper.xpt[0, 2])
    assert np.isclose(lower.psi_bndry, lower.xpt[0, 2])

    # disjoint cores, each on its own side, each carrying its own current
    assert not np.any(upper.limiter_core_mask & lower.limiter_core_mask)
    assert np.all(eq.Z[upper.limiter_core_mask] > 0)
    assert np.all(eq.Z[lower.limiter_core_mask] < 0)
    assert np.allclose(profiles.droplet_currents(), [1e5, 1e5])
    assert np.isclose(eq._current, 2e5)
    assert np.allclose(profiles.jtor, upper.jtor + lower.jtor)

    # up-down symmetric machine, coils and currents -> symmetric solution
    assert np.allclose(upper.opt[0, 2], lower.opt[0, 2], rtol=1e-3)
    assert upper.limiter_core_mask.sum() == lower.limiter_core_mask.sum()

    # the equilibrium keeps an independent copy of the composite profile
    assert isinstance(eq._profiles, DoubleDroplet)
    assert eq._profiles.droplets[0] is not upper
    assert np.allclose(eq._profiles.droplet_currents(), [1e5, 1e5])


def test_droplets_carry_independent_currents(eq):
    profiles = solve(eq, 1.1e5, 0.9e5)
    assert np.allclose(profiles.droplet_currents(), [1.1e5, 0.9e5])
    assert np.isclose(profiles.Ip, 2e5)
    upper, lower = profiles.droplets
    # both droplets stay diverted near their designed positions
    assert np.allclose(upper.opt[0, :2], [R_AXIS, Z_AXIS], atol=0.05)
    assert np.allclose(lower.opt[0, :2], [R_AXIS, -Z_AXIS], atol=0.05)
    assert not upper.flag_limiter and not lower.flag_limiter
    # the weaker droplet has the smaller flux well
    assert abs(upper.psi_axis - upper.psi_bndry) > abs(lower.psi_axis - lower.psi_bndry)
    assert upper.limiter_core_mask.sum() > lower.limiter_core_mask.sum()
    assert not np.any(upper.limiter_core_mask & lower.limiter_core_mask)


def test_droplets_on_synthetic_flux(eq):
    """Two flux peaks with a saddle between them: two disjoint droplets."""
    psi = droplet_guess(eq, [1e5, 1e5], [(0.75, 0.6), (0.75, -0.6)], width=0.15)
    profiles = make_profiles(eq, 1e5, 1e5)
    jtor = profiles.Jtor(eq.R, eq.Z, psi)
    upper, lower = profiles.droplets
    assert upper.opt[0, 1] > 0.3 and lower.opt[0, 1] < -0.3
    assert np.allclose(profiles.droplet_currents(), [1e5, 1e5])
    assert np.isclose(np.sum(jtor) * profiles.dRdZ, 2e5)
    assert not np.any(upper.limiter_core_mask & lower.limiter_core_mask)


def test_droplets_input_validation(eq):
    p1 = ConstrainPaxisIp(eq, 3e3, 1e5, 0.5)
    p2 = ConstrainPaxisIp(eq, 3e3, 1e5, 0.5)
    everywhere = np.ones_like(eq.R, dtype=bool)
    with pytest.raises(ValueError, match="overlap"):
        Droplets(eq, [p1, p2], [everywhere, everywhere])
    with pytest.raises(ValueError, match="one search region"):
        Droplets(eq, [p1, p2], [everywhere])
    with pytest.raises(ValueError, match="shape"):
        Droplets(eq, [p1], [np.ones((3, 3), dtype=bool)])
    profiles = DoubleDroplet(eq, p1, p2)
    with pytest.raises(NotImplementedError):
        profiles.Jtor(eq.R, eq.Z, np.zeros_like(eq.R), psi_bndry=0.1)


def test_flux_references_are_per_droplet(eq):
    """Normalised-flux references come from the droplet owning each point."""
    psi = droplet_guess(eq, [1e5, 0.5e5], [(0.75, 0.6), (0.75, -0.6)], width=0.15)
    profiles = make_profiles(eq, 1e5, 0.5e5)
    profiles.Jtor(eq.R, eq.Z, psi)
    upper, lower = profiles.droplets
    assert not np.isclose(upper.psi_axis, lower.psi_axis)

    R = np.array([0.75, 0.75, 0.75])
    Z = np.array([0.6, -0.6, -0.1])
    assert profiles.droplet_index(R, Z).tolist() == [0, 1, 1]
    psi_axis, psi_bndry = profiles.flux_references(R, Z)
    assert np.allclose(psi_axis, [upper.psi_axis, lower.psi_axis, lower.psi_axis])
    assert np.allclose(psi_bndry, [upper.psi_bndry, lower.psi_bndry, lower.psi_bndry])


def test_vacuum_field_has_no_droplet_axis(eq):
    """Without plasma the vacuum field has no interior O-point: no fake axis."""
    psi_vacuum = eq.tokamak.getPsitokamak(vgreen=eq._vgreen)
    profiles = make_profiles(eq, 1e5, 1e5)
    with pytest.raises(ValueError, match="No magnetic axis"):
        profiles.Jtor(eq.R, eq.Z, psi_vacuum)


def test_contour_fallback_on_shallow_droplets(eq):
    """The contour fallback recovers the separatrix of weak droplets."""
    psi = droplet_guess(eq, [3e4, 3e4], [(0.75, 0.6), (0.75, -0.6)], width=0.15)
    profiles = make_profiles(eq, 3e4, 3e4)
    profiles.Jtor(eq.R, eq.Z, psi)
    upper, lower = profiles.droplets
    core, psi_bndry, xpt = profiles._contour_core(
        0, psi, upper.opt[0], [lower.opt[0]], 1.0
    )
    # same boundary as the X-point based flood fill, to within grid accuracy
    assert np.isclose(psi_bndry, upper.xpt[0, 2], rtol=1e-3)
    assert xpt.shape == (1, 3) and np.isclose(xpt[0, 2], psi_bndry)
    assert abs(int(core.sum()) - int(upper.diverted_core_mask.sum())) < 10


def test_copy_does_not_alias_masks(eq):
    psi = droplet_guess(eq, [1e5, 1e5], [(0.75, 0.6), (0.75, -0.6)], width=0.15)
    profiles = make_profiles(eq, 1e5, 1e5)
    profiles.Jtor(eq.R, eq.Z, psi)
    copied = profiles.copy()
    for p, q in zip(profiles.droplets, copied.droplets):
        assert q is not p
        assert q.limiter_core_mask is not p.limiter_core_mask
        assert np.array_equal(q.limiter_core_mask, p.limiter_core_mask)


def test_optimised_large_double_droplet(eq):
    """Stored optimised design (example 12): two large diverted droplets."""
    data = np.load(REPO_ROOT / "examples" / "data" / "double_droplet_SH3.npz")
    for name, current in zip(data["coil_names"], data["coil_currents"]):
        eq.tokamak.set_coil_current(str(name), float(current))
    eq.set_plasma_psi(data["plasma_psi"])
    paxis, Ip, fvac, alpha_m, alpha_n = data["profile"]
    profiles = DoubleDroplet(
        eq,
        *[
            ConstrainPaxisIp(eq, paxis, Ip, fvac, alpha_m=alpha_m, alpha_n=alpha_n)
            for _ in range(2)
        ],
    )
    solver = GSstaticsolver.NKGSsolver(eq)
    solver.forward_solve(eq, profiles, 1e-8, suppress=True)
    assert solver.relative_change < 1e-8

    upper, lower = profiles.droplets
    assert not upper.flag_limiter and not lower.flag_limiter
    assert np.allclose(profiles.droplet_currents(), [4e5, 4e5])
    assert np.allclose(upper.opt[0, :2], [0.872, 0.566], atol=0.03)
    assert np.allclose(lower.opt[0, :2], [0.872, -0.566], atol=0.03)
    assert np.allclose(upper.xpt[0, :2], [0.661, 1.062], atol=0.03)
    assert np.allclose(lower.xpt[0, :2], [0.661, -1.062], atol=0.03)
    area = [p.limiter_core_mask.sum() * profiles.dRdZ for p in profiles.droplets]
    assert np.allclose(area, 0.379, atol=0.02)
    assert not np.any(upper.limiter_core_mask & lower.limiter_core_mask)
